//! Company AI validation guideline catalog. Faithful port of
//! `guidelines/catalog.js`, plus Rust-only additions with no JS-original
//! equivalent (Dockerfile/compose container rules, GitHub Actions
//! hardening, defusedxml, TLS/JWT verification, debug mode, CORS) added
//! after the port. Each guideline is a static rule a developer/agent can be
//! checked against during development, independent of the full Ignite
//! onboarding pipeline.

use serde::Serialize;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Severity {
    Error,
    Warning,
}

#[derive(Debug, Clone, Serialize)]
