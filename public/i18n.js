// Ignite web UI translations — static UI chrome only (buttons, labels,
// headers, modals, tooltips, placeholders). Server-generated text (phase
// titles/logs, finding summaries/categories/severities, CWE/OWASP ids, tool
// output, file paths, URLs, JSON, raw API error messages) is intentionally
// NEVER translated here — it comes from the Rust backend and stays exactly
// as the API sends it. See CLAUDE.md's "Internationalization" section.
//
// `en` is the source of truth (matches index.html's original English copy
// verbatim). Every other locale must cover every `en` key — a missing key
// silently falls back to English (see index.html's t()), so an incomplete
// translation degrades gracefully rather than breaking.
//
// Keys with `{name}`-style placeholders are filled in via t(key, vars) —
// see the call sites in index.html for which vars each one needs.
//
// Known simplification: a few count-driven strings (result.allCleanWithIssues,
// history.documentCount, history.issueCount, review.selectedCount) use an
// English-style "finding(s)" construction in every locale rather than each
// language's real plural-agreement rules (no plural-rule engine here) — a
// deliberate compromise, not an oversight.
